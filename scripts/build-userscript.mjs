// Builds crt-tv-frame.user.js (for Safari on iPhone/iPad via the Userscripts app,
// or Tampermonkey/Violentmonkey elsewhere) from the extension's source files.
// Usage: node scripts/build-userscript.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFileSync(join(root, f), 'utf8').trim();
const { version, description } = JSON.parse(read('manifest.json'));
const raw = 'https://raw.githubusercontent.com/MmedaraJ/old-tv-extension/main';

const out = `// ==UserScript==
// @name         CRT TV Frame
// @namespace    https://github.com/MmedaraJ/old-tv-extension
// @version      ${version}
// @description  ${description}
// @match        http://*/*
// @match        https://*/*
// @run-at       document-idle
// @grant        none
// @icon         ${raw}/icons/icon128.png
// @downloadURL  ${raw}/crt-tv-frame.user.js
// @updateURL    ${raw}/crt-tv-frame.user.js
// ==/UserScript==

// Generated by scripts/build-userscript.mjs from frame.js and content.js. Do not edit
// the code below by hand; change the extension source and rebuild instead.

// ---- Settings: edit these to taste ----
const CRT_TV_FRAME_SETTINGS = {
  theme: 'walnut', // 'walnut' | 'black' | 'beige' | 'red'
  size: 1, // frame thickness, 0.4 - 2
  scanlines: 30, // 0 (off) - 100
  glass: true, // curved-glass vignette and glare
  panel: true, // side knob panel when there's room
  label: 'SOLID STATE', // badge text on the set
  disabledSites: [], // e.g. ['www.example.com']
};
// ---------------------------------------

${read('frame.js')}

Object.assign(globalThis.CRTFrame.DEFAULTS, CRT_TV_FRAME_SETTINGS, { enabled: true });
globalThis.CRTFrame.standalone = true;

${read('content.js')}
`;

writeFileSync(join(root, 'crt-tv-frame.user.js'), out);
console.log('wrote crt-tv-frame.user.js');
